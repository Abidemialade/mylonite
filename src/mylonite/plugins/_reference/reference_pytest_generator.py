"""Reference pytest generator — emits a real testkit-based regression test.

Given a confirmed :class:`ExploitRecord`, :meth:`ReferencePytestGenerator.emit`
renders a deterministic, self-contained pytest file. The emitted test imports
the public :mod:`mylonite.testkit` API and, at runtime, replays the recorded
attack against the GUARDED reference twin via
:func:`mylonite.testkit.assert_guard_holds` — the offline regression gate.

Two properties are load-bearing:

* **Deterministic.** No LLM call, no timestamp, no randomness; the taxonomy IDs
  are sorted before rendering. The same exploit always emits byte-identical
  source, so the output is snapshot-testable.
* **Collects without data files.** ``load_exploit`` / ``assert_guard_holds`` live
  INSIDE the test function body (not at module level), so the file *collects*
  cleanly even before the ``exploit_<pattern_id>.json`` artefact / fixtures are
  present. Only running the test needs them.

Every emitted marker (``mylonite_security``, the bounded OWASP
``owasp_llm0N`` / ``owasp_asi0N`` set, plus the bundled-taxonomy ATLAS
``atlas_*`` and NIST ``nist_*`` sets) is registered by the bundled pytest
plugin (``mylonite.testkit._pytest_plugin``, auto-loaded via the ``pytest11``
entry point), so the file is warning-free even under ``filterwarnings = error``.
"""

from __future__ import annotations

from typing import ClassVar, Literal

from mylonite.contracts import ExploitRecord, GeneratedTest, TestGeneratorBase
from mylonite.contracts.test_generator import CONTRACT_VERSION
from mylonite.testkit._pytest_plugin import (
    MYLONITE_SECURITY_MARKER,
    REGISTERED_ATLAS_MARKERS,
    REGISTERED_NIST_MARKERS,
    REGISTERED_OWASP_MARKERS,
    _marker_name,
)

_TEMPLATE = '''"""Auto-generated by mylonite — security regression test for `{pattern_id}` \
against `{target_id}`.

Compliance: OWASP LLM {owasp_llm} · OWASP ASI {owasp_asi} · \
MITRE ATLAS {mitre_atlas} · NIST {nist}.

Regenerate with `mylonite generate`. Do not edit by hand.
"""

from pathlib import Path

import pytest

from mylonite import testkit

{decorators}
def test_security_{slug}() -> None:
    """The guarded twin must resist {pattern_id} ({compliance_inline})."""
    here = Path(__file__).parent
    exploit = testkit.load_exploit(here / "exploit_{pattern_id}.json")
    testkit.assert_guard_holds(exploit, fixtures_dir=here / "fixtures")
'''


def _slugify(pattern_id: str) -> str:
    """Turn a ``pattern_id`` into a valid Python identifier suffix.

    Any character that is not a valid identifier char (``-``, ``.``, etc.) is
    collapsed to ``_``. Deterministic and stable.
    """
    return "".join(ch if ch.isalnum() else "_" for ch in pattern_id)


def _fmt_ids(ids: list[str]) -> str:
    """Render a sorted, comma-joined ID list for the docstring (``—`` if empty)."""
    return ", ".join(sorted(ids)) if ids else "—"


class ReferencePytestGenerator(TestGeneratorBase):
    """Emits a deterministic, testkit-based pytest regression test."""

    contract_version: ClassVar[str] = CONTRACT_VERSION

    def framework(self) -> Literal["pytest", "jest"]:
        return "pytest"

    def emit(self, exploit: ExploitRecord) -> GeneratedTest:
        slug = _slugify(exploit.pattern_id)
        compliance = exploit.compliance

        # Bounded OWASP markers only — and ONLY those the pytest11 plugin actually
        # registers (``REGISTERED_OWASP_MARKERS``). An out-of-range OWASP ID (e.g.
        # a future ``LLM11``) would otherwise emit an unregistered marker, which
        # under ``filterwarnings=error`` turns a consumer's committed test into a
        # hard collection error. Unregistered IDs fall back to the docstring, like
        # ATLAS / NIST.
        markers: list[str] = [f"@pytest.mark.{MYLONITE_SECURITY_MARKER}"]
        for tag in sorted(compliance.owasp_llm) + sorted(compliance.owasp_asi):
            marker_name = f"owasp_{tag.lower()}"
            if marker_name in REGISTERED_OWASP_MARKERS:
                markers.append(f"@pytest.mark.{marker_name}")
        # ATLAS / NIST markers, same registered-set guard: emit only names the
        # pytest11 plugin actually registers (bundled-taxonomy IDs); out-of-
        # taxonomy IDs fall back to the docstring. Shared ``_marker_name`` keeps
        # the emitted names byte-identical to the registered set.
        for atlas_id in sorted(compliance.mitre_atlas):
            marker_name = _marker_name("atlas", atlas_id)
            if marker_name in REGISTERED_ATLAS_MARKERS:
                markers.append(f"@pytest.mark.{marker_name}")
        for nist_id in sorted(compliance.nist_ai_rmf):
            marker_name = _marker_name("nist", nist_id)
            if marker_name in REGISTERED_NIST_MARKERS:
                markers.append(f"@pytest.mark.{marker_name}")
        decorators = "\n".join(markers)

        # Inline compliance summary for the test docstring (sorted, stable).
        inline_parts: list[str] = []
        for llm_id in sorted(compliance.owasp_llm):
            inline_parts.append(llm_id)
        for asi_id in sorted(compliance.owasp_asi):
            inline_parts.append(asi_id)
        for atlas_id in sorted(compliance.mitre_atlas):
            inline_parts.append(atlas_id)
        for nist_id in sorted(compliance.nist_ai_rmf):
            inline_parts.append(nist_id)
        compliance_inline = " · ".join(inline_parts) if inline_parts else "no tags"

        source = _TEMPLATE.format(
            pattern_id=exploit.pattern_id,
            target_id=exploit.target_id,
            slug=slug,
            decorators=decorators,
            compliance_inline=compliance_inline,
            owasp_llm=_fmt_ids(compliance.owasp_llm),
            owasp_asi=_fmt_ids(compliance.owasp_asi),
            mitre_atlas=_fmt_ids(compliance.mitre_atlas),
            nist=_fmt_ids(compliance.nist_ai_rmf),
        )

        return GeneratedTest(
            framework="pytest",
            filename=f"test_security_{slug}.py",
            source=source,
            exploit=exploit,
        )
